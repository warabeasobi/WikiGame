let current = 'en';
const listeners = new Set();

export function detectUiLanguage(nav = typeof navigator !== 'undefined' ? navigator : null) {
  const candidates = [];
  if (nav) {
    if (Array.isArray(nav.languages)) candidates.push(...nav.languages);
    if (nav.language) candidates.push(nav.language);
  }
  for (const raw of candidates) {
    const code = String(raw || '').toLowerCase().split('-')[0];
    if (STRINGS[code]) return code;
  }
  return 'en';
}

export function setUiLanguage(code) {
  const next = STRINGS[code] ? code : 'en';
  if (next === current) return current;
  current = next;
  try { document.documentElement.setAttribute('lang', next); } catch { /* no dom */ }
  for (const fn of listeners) { try { fn(next); } catch (err) { console.error(err); } }
  return current;
}

export function getUiLanguage() { return current; }

export function onLanguageChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key, vars) {
  const table = STRINGS[current] || STRINGS.en;
  let str = table[key] ?? STRINGS.en[key] ?? key;
  if (vars && typeof str === 'string') {
    str = str.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
  }
  return str;
}

export function hasKey(key) {
  return Boolean((STRINGS[current] || {})[key] ?? STRINGS.en[key]);
}

export function listKeys(lang = 'en') {
  return Object.keys(STRINGS[lang] || {});
}

export function missingKeys(lang) {
  const base = new Set(Object.keys(STRINGS.en));
  const target = new Set(Object.keys(STRINGS[lang] || {}));
  return {
    missingInTarget: [...base].filter((k) => !target.has(k)),
    extraInTarget: [...target].filter((k) => !base.has(k)),
  };
}

